#!/usr/bin/env python3
"""Merge and clean generated seed SQL files into one import file.

Fixes what raw Wikidata output cannot guarantee:
- drops rows whose "country" is not a country (Wikidata sometimes returns labels
  like "People", "Earth" or a bare Q-id)
- drops rows with no usable description
- de-duplicates descriptions: several places can share the same Wikipedia opening
  sentence, and repeating it on every card is exactly the thin content search
  engines penalise. The first keeps the real text, the rest get an honest short
  line built from their own name, category and country.
- de-duplicates slugs across files

Usage: python3 scripts/merge-seed.py out.sql in1.sql in2.sql ...
"""

import re
import sys

ROW = re.compile(
    r"^  \('(?P<name>(?:[^']|'')*)', '(?P<slug>[^']*)', '(?P<category>[^']*)', "
    r"'(?P<country>(?:[^']|'')*)', '(?P<region>(?:[^']|'')*)', '(?P<city>(?:[^']|'')*)', "
    r"(?P<lat>-?[\d.]+), (?P<lon>-?[\d.]+), '(?P<desc>(?:[^']|'')*)'\)"
)

NOT_A_COUNTRY = {
    "people", "earth", "world", "europe", "asia", "africa", "oceania", "antarctica",
    "north america", "south america", "q", "unknown", "",
}

HEADER = """-- TerraLens place seed: real places with real coordinates.
--
-- Every row is a Wikidata item that has coordinates (P625), a country (P17) and an
-- English Wikipedia article. The description is that article's opening sentences.
-- Nothing here is invented: no fee, season or access detail is guessed, so those
-- fields carry an honest "check locally" default and the admin fills them in.
--
-- Safe to re-run: rows whose slug already exists are skipped.
--
-- Generated by scripts/build-seed.py and scripts/merge-seed.py. Do not edit by hand.

insert into public.places
  (name, slug, category, country, region, city, latitude, longitude,
   best_season, best_time, access_info, entry_fee, description, status, created_by)
select v.name, v.slug, v.category, v.country, v.region, v.city, v.latitude, v.longitude,
       'Check the best season locally',
       'Check opening times locally',
       'Check access, opening times and conditions locally before travelling.',
       'Varies. Check before you go.',
       v.description, 'draft',
       (select id from public.profiles order by created_at limit 1)
  from (values
"""

FOOTER = """
) as v(name, slug, category, country, region, city, latitude, longitude, description)
where not exists (select 1 from public.places p where p.slug = v.slug);
"""

FALLBACK = {
    "Waterfall": "A waterfall in {country}, documented on Wikipedia. Check local guides for access, the best season and any entry fee before you travel.",
    "Mountain": "A mountain in {country}, documented on Wikipedia. Check local guides for routes, conditions and permits before you climb.",
    "Lake": "A lake in {country}, documented on Wikipedia. Check local guides for access, boat hire and the best season before you visit.",
    "Beach": "A beach in {country}, documented on Wikipedia. Check local guides for access, swimming conditions and facilities before you go.",
    "Forest": "A forest in {country}, documented on Wikipedia. Check local guides for trails, opening times and permits before you visit.",
}


def unq(s):
    return s.replace("''", "'")


def q(s):
    return str(s).replace("'", "''")


def main():
    out_path, inputs = sys.argv[1], sys.argv[2:]
    rows, seen_slug, seen_desc, seen_name = [], set(), set(), set()
    dropped_country = dropped_desc = replaced = 0

    for path in inputs:
        for line in open(path):
            m = ROW.match(line.rstrip("\n"))
            if not m:
                continue
            d = {k: unq(v) for k, v in m.groupdict().items()}
            if d["country"].strip().lower() in NOT_A_COUNTRY:
                dropped_country += 1
                continue
            desc = d["desc"].strip()
            if len(desc) < 60:
                dropped_desc += 1
                continue
            key = re.sub(r"\W+", " ", desc.lower()).strip()
            name_key = d["name"].strip().lower()
            if d["slug"] in seen_slug or name_key in seen_name:
                continue
            if key in seen_desc:
                desc = FALLBACK[d["category"]].format(country=d["country"])
                replaced += 1
            seen_slug.add(d["slug"])
            seen_name.add(name_key)
            seen_desc.add(key)
            d["desc"] = desc
            rows.append(d)

    lines = [
        "  ('{name}', '{slug}', '{category}', '{country}', '{region}', '{city}', {lat}, {lon}, '{desc}')".format(
            name=q(r["name"]), slug=r["slug"], category=r["category"], country=q(r["country"]),
            region=q(r["region"]), city=q(r["city"]), lat=r["lat"], lon=r["lon"], desc=q(r["desc"])
        )
        for r in rows
    ]

    with open(out_path, "w") as f:
        f.write(HEADER + ",\n".join(lines) + FOOTER)

    print(f"{len(rows)} places written to {out_path}")
    print(f"dropped {dropped_country} non-country rows, {dropped_desc} with no usable description")
    print(f"{replaced} repeated descriptions replaced with an honest fallback")


if __name__ == "__main__":
    main()
