const LOCALE_DATA = { en, fr, es, pt, de, sw, ha, yo, ig, zh, ar, hi };

// The remaining locales (ha, yo, ig, zh, ar, hi, ru, ko, id) reuse the English
// strings until their own translations are supplied. English is a better fallback
// than a machine translation of a navigation label, so this is deliberate.
const FALLBACK_ORDER = ["en", "fr", "es", "pt", "de", "sw"];

let current = DEFAULT;
let dict = en;

export function currentLang() {
  return current;
}

export function t(key) {
  if (!key) return "";
  const value = dict[key];
  if (typeof value === "string") return value;
  return en[key] || key;
}

export function setLang(code) {
  const lang = LANGUAGES.find(l => l.code === code);
  if (!lang) return;
  current = code;
  dict = LOCALE_DATA[code] || en;
  try { localStorage.setItem(STORAGE_KEY, code); } catch (_) {}
  if (typeof document !== "undefined") {
    document.documentElement.lang = code;
    applyTranslations(document);
    document.dispatchEvent(new CustomEvent("terralens:lang", { detail: code }));
  }
}

export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    const value = t(el.getAttribute("data-i18n"));
    if (value && value !== el.getAttribute("data-i18n")) el.textContent = value;
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const value = t(el.getAttribute("data-i18n-placeholder"));
    if (value) el.setAttribute("placeholder", value);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const value = t(el.getAttribute("data-i18n-aria"));
    if (value) el.setAttribute("aria-label", value);
  });
}

// Picks a starting language: an explicit ?lang=, then a saved choice, then the
// browser's language if we have that language, then English.
export function initLang() {
  let code = DEFAULT;
  try {
    const fromUrl = new URLSearchParams(location.search).get("lang");
    if (fromUrl && LANGUAGES.some(l => l.code === fromUrl)) code = fromUrl;
  } catch (_) {}
  if (code === DEFAULT) {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && LANGUAGES.some(l => l.code === saved)) code = saved;
    } catch (_) {}
  }
  if (code === DEFAULT) {
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    if (LANGUAGES.some(l => l.code === nav) && FALLBACK_ORDER.includes(nav)) code = nav;
  }
  setLang(code);
  return code;
}

export function langUrl(code, path = location.pathname) {
  return `${path}?lang=${encodeURIComponent(code)}`;
}
